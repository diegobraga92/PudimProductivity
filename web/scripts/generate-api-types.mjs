#!/usr/bin/env node
// Generates TypeScript client types from the OpenAPI specs in api/openapi/ into
// web/src/api/generated/.
//
// The OpenAPI specs are the source of truth for the HTTP contract. The generated
// types are committed and imported by the hand-written clients in web/src/api/
// so that any spec change that breaks a client breaks the web build.
//
//   npm run generate:api   — regenerate (commit the output)
//   npm run check:api      — regenerate and fail if the output drifted
//
// CI runs check:api whenever api/** changes (see .github/workflows/web-ci.yml).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const outDir = join(here, "..", "src", "api", "generated");
mkdirSync(outDir, { recursive: true });

const SPECS = [
  ["health-v1.yaml", "health-v1.ts"],
  ["pomodoro-v1.yaml", "pomodoro-v1.ts"],
  ["tasks-v1.yaml", "tasks-v1.ts"],
  ["recipes-v1.yaml", "recipes-v1.ts"],
  ["library-v1.yaml", "library-v1.ts"],
  ["admin-v1.yaml", "admin-v1.ts"],
];

// Same banner the openapi-typescript CLI emits; marks the file as generated.
const HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

for (const [spec, out] of SPECS) {
  const specPath = pathToFileURL(join(root, "api", "openapi", spec));
  const ast = await openapiTS(specPath);
  writeFileSync(join(outDir, out), HEADER + astToString(ast));
  console.log(`Generated ${out} from api/openapi/${spec}`);
}
